"""OpenAI Chat Completions response and stream API models."""

from __future__ import annotations

from time import time
from typing import Annotated, Any, Literal

from pydantic import BaseModel, Field

from molto.types.openai.chat_completions.models_request import (
    ChatCompletionFunctionCall,
    ChatCompletionToolCall,
)

# ---------------------------------------------------------------------------
# Response types
# ---------------------------------------------------------------------------


class ChatCompletionTokenLogprobTopLogprob(BaseModel):
    token: Annotated[
        str,
        Field(description="The token."),
    ]
    logprob: Annotated[
        float,
        Field(description="The log probability of this token."),
    ]
    bytes: Annotated[
        list[int] | None,
        Field(description="A list of integers representing the bytes of the token."),
    ] = None


class ChatCompletionTokenLogprob(BaseModel):
    token: Annotated[
        str,
        Field(description="The token."),
    ]
    logprob: Annotated[
        float,
        Field(description="The log probability of this token."),
    ]
    bytes: Annotated[
        list[int] | None,
        Field(description="A list of integers representing the bytes of the token."),
    ] = None
    top_logprobs: Annotated[
        list[ChatCompletionTokenLogprobTopLogprob],
        Field(description="List of the most likely tokens and their log probability."),
    ] = Field(default_factory=list)


class ChatCompletionLogprobs(BaseModel):
    content: Annotated[
        list[ChatCompletionTokenLogprob] | None,
        Field(description="A list of message content tokens with log probability information."),
    ] = None
    refusal: Annotated[
        list[ChatCompletionTokenLogprob] | None,
        Field(description="A list of refusal tokens with log probability information."),
    ] = None


class ChatCompletionAudio(BaseModel):
    id: Annotated[
        str,
        Field(description="The unique identifier for the generated audio."),
    ]
    data: Annotated[
        str,
        Field(description="Base64-encoded audio bytes generated by the model."),
    ]
    expires_at: Annotated[
        int,
        Field(ge=0, description="The Unix timestamp when the audio expires."),
    ]
    transcript: Annotated[
        str,
        Field(description="The transcript of the generated audio."),
    ]


class ChatCompletionResponseMessage(BaseModel):
    role: Annotated[
        Literal["assistant"],
        Field(description="The role of the author of this message. Always `assistant`."),
    ] = "assistant"
    content: Annotated[
        str | None,
        Field(description="The contents of the assistant message."),
    ] = None
    refusal: Annotated[
        str | None,
        Field(description="The refusal message by the assistant."),
    ] = None
    annotations: Annotated[
        list[dict[str, Any]],
        Field(description="Annotations for the assistant message."),
    ] = Field(default_factory=list)
    audio: Annotated[
        ChatCompletionAudio | None,
        Field(description="Generated audio returned by the model."),
    ] = None
    tool_calls: Annotated[
        list[ChatCompletionToolCall] | None,
        Field(description="The tool calls generated by the model."),
    ] = None
    function_call: Annotated[
        ChatCompletionFunctionCall | None,
        Field(description="Deprecated: use `tool_calls` instead."),
    ] = None


class ChatCompletionPromptTokensDetails(BaseModel):
    cached_tokens: int = 0
    audio_tokens: int = 0
    image_tokens: int = 0
    text_tokens: int = 0


class ChatCompletionCompletionTokensDetails(BaseModel):
    reasoning_tokens: int = 0
    audio_tokens: int = 0
    image_tokens: int = 0
    text_tokens: int = 0
    accepted_prediction_tokens: int = 0
    rejected_prediction_tokens: int = 0


class ChatCompletionUsage(BaseModel):
    prompt_tokens: Annotated[
        int,
        Field(description="Number of tokens in the prompt."),
    ]
    completion_tokens: Annotated[
        int,
        Field(description="Number of tokens in the generated completion."),
    ]
    total_tokens: Annotated[
        int,
        Field(description="Total number of tokens used."),
    ]
    prompt_tokens_details: ChatCompletionPromptTokensDetails = Field(
        default_factory=ChatCompletionPromptTokensDetails
    )
    completion_tokens_details: ChatCompletionCompletionTokensDetails = Field(
        default_factory=ChatCompletionCompletionTokensDetails
    )


FinishReason = Literal[
    "stop",
    "length",
    "tool_calls",
    "content_filter",
    "function_call",
]


class ChatCompletionChoice(BaseModel):
    index: Annotated[
        int,
        Field(description="The index of the choice in the list of choices."),
    ]
    message: Annotated[
        ChatCompletionResponseMessage,
        Field(description="A chat completion message generated by the model."),
    ]
    logprobs: Annotated[
        ChatCompletionLogprobs | None,
        Field(description="Log probability information for the choice."),
    ] = None
    finish_reason: Annotated[
        FinishReason | None,
        Field(
            description=(
                "The reason the model stopped generating tokens. "
                "One of `stop`, `length`, `tool_calls`, or `content_filter`."
            ),
        ),
    ] = None


class OpenAIChatCompletionResponse(BaseModel):
    id: Annotated[
        str | None,
        Field(
            default=None,
            description="A unique identifier for the chat completion.",
        ),
    ] = None
    choices: Annotated[
        list[ChatCompletionChoice],
        Field(description="A list of chat completion choices."),
    ]
    created: Annotated[
        int,
        Field(
            default_factory=lambda: int(time()),
            description="The Unix timestamp of when the chat completion was created.",
        ),
    ]
    model: Annotated[
        str,
        Field(description="The model used for the chat completion."),
    ]
    object: Annotated[
        Literal["chat.completion"],
        Field(description="The object type. Always `chat.completion`."),
    ] = "chat.completion"
    service_tier: Annotated[
        str | None,
        Field(description="The service tier used to process the request."),
    ] = None
    system_fingerprint: Annotated[
        str | None,
        Field(description="The backend fingerprint that ran the model."),
    ] = None
    usage: Annotated[
        ChatCompletionUsage | None,
        Field(description="Usage statistics for the completion request."),
    ] = None


# ---------------------------------------------------------------------------
# Streaming response types
# ---------------------------------------------------------------------------


class ChatCompletionStreamFunctionCall(BaseModel):
    name: Annotated[
        str | None,
        Field(description="The name of the function being called."),
    ] = None
    arguments: Annotated[
        str | None,
        Field(description="The partial arguments delta."),
    ] = None


class ChatCompletionStreamToolCall(BaseModel):
    index: Annotated[
        int,
        Field(description="The index of the tool call in the choice."),
    ]
    id: Annotated[
        str | None,
        Field(description="The ID of the tool call."),
    ] = None
    type: Annotated[
        Literal["function"] | None,
        Field(description="The type of the tool. Always `function` when present."),
    ] = None
    function: Annotated[
        ChatCompletionStreamFunctionCall | None,
        Field(description="Function call delta."),
    ] = None


class ChatCompletionStreamDelta(BaseModel):
    role: Annotated[
        Literal["assistant"] | None,
        Field(description="The role of the author of this message."),
    ] = None
    content: Annotated[
        str | None,
        Field(description="The contents of the chunk message."),
    ] = None
    tool_calls: Annotated[
        list[ChatCompletionStreamToolCall] | None,
        Field(description="The tool call deltas generated by streamed model responses."),
    ] = None
    refusal: Annotated[
        str | None,
        Field(description="The refusal message by the assistant."),
    ] = None
    audio: Annotated[
        ChatCompletionAudio | None,
        Field(description="Generated audio returned by the model."),
    ] = None


class ChatCompletionStreamChoice(BaseModel):
    index: Annotated[
        int,
        Field(description="The index of the choice in the list of choices."),
    ]
    delta: Annotated[
        ChatCompletionStreamDelta,
        Field(description="A chat completion delta generated by streamed model responses."),
    ]
    logprobs: Annotated[
        ChatCompletionLogprobs | None,
        Field(description="Log probability information for the choice."),
    ] = None
    finish_reason: Annotated[
        FinishReason | None,
        Field(description="The reason the model stopped generating tokens."),
    ] = None


class OpenAIChatCompletionChunk(BaseModel):
    id: Annotated[
        str | None,
        Field(
            default=None,
            description="A unique identifier for the chat completion chunk.",
        ),
    ] = None
    choices: Annotated[
        list[ChatCompletionStreamChoice],
        Field(description="A list of chat completion choices."),
    ]
    created: Annotated[
        int,
        Field(
            default_factory=lambda: int(time()),
            description="The Unix timestamp of when the chat completion chunk was created.",
        ),
    ]
    model: Annotated[
        str,
        Field(description="The model used for the chat completion."),
    ]
    object: Annotated[
        Literal["chat.completion.chunk"],
        Field(description="The object type. Always `chat.completion.chunk`."),
    ] = "chat.completion.chunk"
    service_tier: Annotated[
        str | None,
        Field(description="The service tier used to process the request."),
    ] = None
    system_fingerprint: Annotated[
        str | None,
        Field(description="The backend fingerprint that ran the model."),
    ] = None
    obfuscation: Annotated[
        str | None,
        Field(description="Padding added to the stream chunk by the provider."),
    ] = None
    usage: Annotated[
        ChatCompletionUsage | None,
        Field(description="Usage statistics for the completion request."),
    ] = None

    def as_chunk(self) -> str:
        return f"data: {self.model_dump_json(exclude_none=True)}\n\n"
