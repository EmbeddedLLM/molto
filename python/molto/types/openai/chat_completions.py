def _convert_messages(
    messages: list[ChatCompletionMessage],
) -> list[InputHistoryItem]:
    result: list[InputHistoryItem] = []
    for msg in messages:
        if isinstance(msg, ChatCompletionSystemMessage):
            result.append(SystemMessage(content=msg.content or ""))

        elif isinstance(msg, ChatCompletionUserMessage):
            if isinstance(msg.content, str):
                result.append(UserMessage(content=msg.content))
            elif isinstance(msg.content, list):
                parts: list[ContentPart] = []
                for c in msg.content:
                    if isinstance(c, ChatCompletionContentPartText):
                        parts.append(TextPart(text=c.text))
                    else:
                        parts.append(
                            ImagePart(
                                url=c.image_url.url,
                                detail=c.image_url.detail,
                            )
                        )
                result.append(UserMessage(content=parts))
            else:
                result.append(UserMessage(content=""))

        elif isinstance(msg, ChatCompletionAssistantMessage):
            tool_calls: list[AgentToolCall] = []
            if msg.tool_calls:
                for tc in msg.tool_calls:
                    args, raw_args = _safe_tool_args(tc.function.arguments)
                    tool_calls.append(
                        AgentToolCall(
                            tool_call_id=tc.id,
                            tool_name=tc.function.name,
                            args=args,
                            raw_args=raw_args,
                        )
                    )
            if msg.function_call is not None:
                args, raw_args = _safe_tool_args(msg.function_call.arguments)
                tool_calls.append(
                    AgentToolCall(
                        tool_call_id=uuid7_str("call_"),
                        tool_name=msg.function_call.name,
                        args=args,
                        raw_args=raw_args,
                    )
                )
            if tool_calls:
                result.append(AgentToolCalls(tool_calls=tool_calls))
            content_str = msg.content or msg.refusal or ""
            if content_str:
                result.append(AgentMessage(content=content_str))

        elif isinstance(msg, ChatCompletionToolMessage):
            result.append(
                AgentToolResult(
                    tool_call_id=msg.tool_call_id,
                    tool_name=msg.name or "",
                    result=msg.content or "",
                )
            )

        elif isinstance(msg, ChatCompletionFunctionMessage):
            result.append(
                AgentToolResult(
                    tool_call_id="",
                    tool_name=msg.name,
                    result=msg.content or "",
                )
            )

    return result


