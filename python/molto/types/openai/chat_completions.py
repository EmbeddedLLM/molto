class OpenAIChatCompletionRequest(BaseModel):
    messages: Annotated[
        list[ChatCompletionMessage],
        Field(description="A list of messages comprising the conversation so far."),
    ]
    model: Annotated[
        str,
        Field(description="The model to use for generating the chat completion."),
    ]
    frequency_penalty: Annotated[
        float | None,
        Field(
            ge=-2,
            le=2,
            description=(
                "Number between -2.0 and 2.0. Positive values penalize new tokens based on their "
                "existing frequency in the text so far."
            ),
        ),
    ] = None
    logprobs: Annotated[
        bool | None,
        Field(
            description="Whether to return log probabilities of the output tokens or not.",
        ),
    ] = None
    top_logprobs: Annotated[
        int | None,
        Field(
            ge=0,
            le=20,
            description=(
                "An integer between 0 and 20 specifying the number of most likely tokens to return "
                "at each token position."
            ),
        ),
    ] = None
    max_tokens: Annotated[
        int | None,
        Field(
            ge=1,
            description=(
                "The maximum number of tokens that can be generated in the chat completion."
            ),
        ),
    ] = None
    max_completion_tokens: Annotated[
        int | None,
        Field(
            ge=1,
            description=(
                "An upper bound for the number of tokens that can be generated for a completion, "
                "including visible output tokens and reasoning tokens."
            ),
        ),
    ] = None
    n: Annotated[
        int | None,
        Field(
            ge=1,
            description="How many chat completion choices to generate for each input message.",
        ),
    ] = None
    presence_penalty: Annotated[
        float | None,
        Field(
            ge=-2,
            le=2,
            description=(
                "Number between -2.0 and 2.0. Positive values penalize new tokens based on "
                "whether they appear in the text so far."
            ),
        ),
    ] = None
    response_format: Annotated[
        ChatCompletionResponseFormat | None,
        Field(description="An object specifying the format that the model must output."),
    ] = None
    seed: Annotated[
        int | None,
        Field(
            description="If specified, our system will make a best effort to sample deterministically."
        ),
    ] = None
    stop: Annotated[
        str | list[str] | None,
        Field(description="Up to 4 sequences where the API will stop generating further tokens."),
    ] = None
    stream: Annotated[
        bool,
        Field(
            description="If set to true, the model response data will be streamed as it is generated."
        ),
    ] = False
    stream_options: Annotated[
        ChatCompletionStreamOptions | None,
        Field(description="Options for streaming response."),
    ] = None
    temperature: Annotated[
        float | None,
        Field(
            gt=0,
            lt=2,
            description="What sampling temperature to use, between 0 and 2.",
        ),
    ] = None
    top_p: Annotated[
        float | None,
        Field(
            ge=0,
            le=1,
            description="An alternative to sampling with temperature, called nucleus sampling.",
        ),
    ] = None
    tools: Annotated[
        list[ChatCompletionTool] | None,
        Field(description="A list of tools the model may call."),
    ] = None
    tool_choice: Annotated[
        ChatCompletionToolChoiceOption,
        Field(description="Controls which tool is called by the model."),
    ] = "auto"
    parallel_tool_calls: Annotated[
        bool,
        Field(description="Whether to enable parallel function calling."),
    ] = True
    user: Annotated[
        str | None,
        Field(description="A unique identifier representing your end-user."),
    ] = None
    reasoning_effort: Annotated[
        Literal["none", "minimal", "low", "medium", "high", "xhigh"] | None,
        Field(description="Constrains effort on reasoning for reasoning models."),
    ] = None

    def to_ir(self) -> Input:
        ir_tools: list[FunctionTool] | None = None
        if self.tools:
            ir_tools = []
            for t in self.tools:
                ir_tools.append(
                    FunctionTool(
                        name=t.function.name,
                        parameters=t.function.parameters,
                        strict=t.function.strict or True,
                        description=t.function.description,
                    )
                )

        tc = self.tool_choice
        if isinstance(tc, ChatCompletionToolCall):
            ir_tool_choice: Any = FunctionToolChoice(name=tc.function.name)
        else:
            ir_tool_choice = tc

        text_format = None
        if self.response_format is not None:
            if isinstance(self.response_format, ChatCompletionResponseFormatText):
                text_format = TextFormat()
            elif isinstance(self.response_format, ChatCompletionResponseFormatJsonObject):
                text_format = JsonObjectFormat()
            elif isinstance(self.response_format, ChatCompletionResponseFormatJsonSchema):
                text_format = JsonSchemaFormat(
                    name=self.response_format.name or "",
                    json_schema=self.response_format.json_schema,
                    strict=self.response_format.strict or False,
                    description=self.response_format.description,
                )

        max_output_tokens = self.max_completion_tokens or self.max_tokens

        return Input(
            model=self.model,
            stream=self.stream,
            input=_convert_messages(self.messages),
            instructions=None,
            temperature=self.temperature,
            top_p=self.top_p,
            max_output_tokens=max_output_tokens,
            reasoning_effort=self.reasoning_effort,
            reasoning_summary=None,
            top_logprobs=self.top_logprobs if self.logprobs else None,
            parallel_tool_calls=self.parallel_tool_calls,
            max_tool_calls=None,
            text_format=text_format,
            tools=ir_tools,
            tool_choice=ir_tool_choice,
            include=None,
            previous_response_id=None,
            metadata=None,
        )


